import assert from "node:assert/strict";
import { mkdtemp, readFile, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import Ajv2020 from "ajv/dist/2020.js";
import { _ } from "ajv/dist/compile/codegen/index.js";
import standaloneCode from "ajv/dist/standalone/index.js";
import { compile } from "json-schema-to-typescript";

const frontendRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const generatedDirectory = resolve(frontendRoot, "src/api/generated");
const schemaPath = resolve(generatedDirectory, "dashboardResponseSchemas.json");
const outputNames = [
  "dashboardResponses.d.ts",
  "dashboardValidators.js",
  "dashboardValidators.d.ts",
];
const check = process.argv.slice(2).includes("--check");

function requireSchemaMap(value) {
  assert(value && typeof value === "object" && !Array.isArray(value), "response schema export must be an object");
  for (const key of ["dashboard_context", "dashboard_funds"]) {
    assert(value[key] && typeof value[key] === "object" && !Array.isArray(value[key]), `missing response schema: ${key}`);
  }
  return value;
}

function indent(source) {
  return source.trim().split("\n").map(line => line ? `  ${line}` : "").join("\n");
}

async function generatedTypes(schemas) {
  const options = {
    bannerComment: "",
    additionalProperties: false,
    enableConstEnums: false,
    style: { singleQuote: false, semi: true, tabWidth: 2, trailingComma: "all" },
    unknownAny: false,
  };
  const context = await compile(schemas.dashboard_context, "DashboardContextResponse", options);
  const funds = await compile(schemas.dashboard_funds, "DashboardFundsResponse", options);
  return `// Generated by scripts/generate-dashboard-contracts.mjs. Do not edit.\n\n`
    + `export namespace DashboardContextContract {\n${indent(context)}\n}\n\n`
    + `export namespace DashboardFundsContract {\n${indent(funds)}\n}\n\n`
    + `export type DashboardContextResponse = DashboardContextContract.DashboardContextResponse;\n`
    + `export type DashboardFundsResponse = DashboardFundsContract.DashboardFundsResponse;\n`;
}

function generatedValidators(schemas) {
  const ajv = new Ajv2020({
    allErrors: true,
    inlineRefs: false,
    code: { esm: true, source: true },
    strict: true,
    validateFormats: false,
  });
  ajv.addKeyword({
    keyword: "x-fen-int64",
    schemaType: "boolean",
    type: "string",
    errors: false,
    code(context) {
      if (context.schema) {
        context.fail(_`!/^(0|-?[1-9][0-9]*)$/.test(${context.data}) || String(BigInt(${context.data})) !== ${context.data} || BigInt(${context.data}) < -9223372036854775808n || BigInt(${context.data}) > 9223372036854775807n`);
      }
    },
  });
  ajv.addSchema(schemas.dashboard_context, "dashboard_context");
  ajv.addSchema(schemas.dashboard_funds, "dashboard_funds");
  return `// Generated by scripts/generate-dashboard-contracts.mjs. Do not edit.\n`
    + standaloneCode(ajv, {
      validateDashboardContextResponse: "dashboard_context",
      validateDashboardFundsResponse: "dashboard_funds",
    });
}

function generatedValidatorTypes() {
  return `// Generated by scripts/generate-dashboard-contracts.mjs. Do not edit.\n\n`
    + `import type { DashboardContextResponse, DashboardFundsResponse } from "./dashboardResponses";\n\n`
    + `export interface DashboardValidationError {\n`
    + `  instancePath: string;\n`
    + `  schemaPath: string;\n`
    + `  keyword: string;\n`
    + `  params: Record<string, unknown>;\n`
    + `  message?: string;\n`
    + `}\n\n`
    + `export interface DashboardResponseValidator<T> {\n`
    + `  (value: unknown): value is T;\n`
    + `  errors?: DashboardValidationError[] | null;\n`
    + `}\n\n`
    + `export const validateDashboardContextResponse: DashboardResponseValidator<DashboardContextResponse>;\n`
    + `export const validateDashboardFundsResponse: DashboardResponseValidator<DashboardFundsResponse>;\n`;
}

async function buildOutputs(targetDirectory) {
  const schemas = requireSchemaMap(JSON.parse(await readFile(schemaPath, "utf8")));
  const outputs = {
    "dashboardResponses.d.ts": await generatedTypes(schemas),
    "dashboardValidators.js": generatedValidators(schemas),
    "dashboardValidators.d.ts": generatedValidatorTypes(),
  };
  await Promise.all(Object.entries(outputs).map(([name, content]) => writeFile(join(targetDirectory, name), content, "utf8")));
}

if (check) {
  const temporaryDirectory = await mkdtemp(join(tmpdir(), "dashboard-contracts-"));
  try {
    await buildOutputs(temporaryDirectory);
    for (const name of outputNames) {
      const generated = await readFile(join(temporaryDirectory, name));
      const tracked = await readFile(join(generatedDirectory, name));
      assert(generated.equals(tracked), `${name} is stale; run npm run contracts:generate`);
    }
  } finally {
    await rm(temporaryDirectory, { recursive: true, force: true });
  }
} else {
  await buildOutputs(generatedDirectory);
}
