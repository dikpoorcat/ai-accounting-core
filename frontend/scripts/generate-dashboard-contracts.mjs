import assert from "node:assert/strict";
import { mkdtemp, readFile, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import Ajv2020 from "ajv/dist/2020.js";
import { _ } from "ajv/dist/compile/codegen/index.js";
import standaloneCode from "ajv/dist/standalone/index.js";
import { compile } from "json-schema-to-typescript";

const frontendRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const generatedDirectory = resolve(frontendRoot, "src/api/generated");
const schemaPath = resolve(generatedDirectory, "dashboardResponseSchemas.json");
const outputNames = ["dashboardResponses.d.ts", "dashboardValidators.js", "dashboardValidators.d.ts"];
const check = process.argv.slice(2).includes("--check");

// A Python response model is browser-visible only after it is intentionally listed here.
const contracts = [
  ["dashboard_context", "DashboardContext"],
  ["dashboard_brief", "DashboardBrief"],
  ["dashboard_funds", "DashboardFunds"],
  ["dashboard_employees", "DashboardEmployees"],
  ["dashboard_assets", "DashboardAssets"],
  ["dashboard_business_status", "DashboardBusinessStatus"],
  ["dashboard_quarterly_report", "DashboardQuarterlyReport"],
  ["dashboard_period_preparation", "DashboardPeriodPreparation"],
  ["dashboard_close_review", "DashboardCloseReview"],
  ["browser_jobs", "BrowserJobs"],
  ["browser_security_status", "BrowserSecurityStatus"],
  ["report_export_receipt", "ReportExportReceipt"],
];

function requireSchemaMap(value) {
  assert(value && typeof value === "object" && !Array.isArray(value), "response schema export must be an object");
  for (const [key] of contracts) {
    assert(value[key] && typeof value[key] === "object" && !Array.isArray(value[key]), `missing response schema: ${key}`);
  }
  return value;
}

function indent(source) {
  return source.trim().split("\n").map(line => line ? `  ${line}` : "").join("\n");
}

async function generatedTypes(schemas) {
  const options = {
    bannerComment: "", additionalProperties: false, enableConstEnums: false,
    style: { singleQuote: false, semi: true, tabWidth: 2, trailingComma: "all" }, unknownAny: false,
  };
  const namespaces = [];
  const aliases = [];
  for (const [key, name] of contracts) {
    const responseName = `${name}Response`;
    const generated = await compile(schemas[key], responseName, options);
    namespaces.push(`export namespace ${name}Contract {\n${indent(generated)}\n}`);
    aliases.push(`export type ${responseName} = ${name}Contract.${responseName};`);
  }
  return `// Generated by scripts/generate-dashboard-contracts.mjs. Do not edit.\n\n${namespaces.join("\n\n")}\n\n${aliases.join("\n")}\n`;
}

function generatedValidators(schemas) {
  const ajv = new Ajv2020({ allErrors: true, inlineRefs: false, code: { esm: true, source: true }, strict: true, validateFormats: false });
  ajv.addKeyword({
    keyword: "x-fen-int64", schemaType: "boolean", type: "string", errors: false,
    code(context) {
      if (context.schema) context.fail(_`!/^(0|-?[1-9][0-9]*)$/.test(${context.data}) || String(BigInt(${context.data})) !== ${context.data} || BigInt(${context.data}) < -9223372036854775808n || BigInt(${context.data}) > 9223372036854775807n`);
    },
  });
  for (const [key] of contracts) ajv.addSchema(schemas[key], key);
  return `// Generated by scripts/generate-dashboard-contracts.mjs. Do not edit.\n${standaloneCode(ajv, Object.fromEntries(contracts.map(([key, name]) => [`validate${name}Response`, key])))}`;
}

function generatedValidatorTypes() {
  const responseNames = contracts.map(([, name]) => `${name}Response`);
  return `// Generated by scripts/generate-dashboard-contracts.mjs. Do not edit.\n\n`
    + `import type { ${responseNames.join(", ")} } from "./dashboardResponses";\n\n`
    + `export interface DashboardValidationError {\n  instancePath: string;\n  schemaPath: string;\n  keyword: string;\n  params: Record<string, unknown>;\n  message?: string;\n}\n\n`
    + `export interface DashboardResponseValidator<T> {\n  (value: unknown): value is T;\n  errors?: DashboardValidationError[] | null;\n}\n\n`
    + contracts.map(([, name]) => `export const validate${name}Response: DashboardResponseValidator<${name}Response>;`).join("\n") + "\n";
}

async function buildOutputs(targetDirectory) {
  const schemas = requireSchemaMap(JSON.parse(await readFile(schemaPath, "utf8")));
  const outputs = {
    "dashboardResponses.d.ts": await generatedTypes(schemas),
    "dashboardValidators.js": generatedValidators(schemas),
    "dashboardValidators.d.ts": generatedValidatorTypes(),
  };
  await Promise.all(Object.entries(outputs).map(([name, content]) => writeFile(join(targetDirectory, name), content, "utf8")));
}

if (check) {
  const temporaryDirectory = await mkdtemp(join(tmpdir(), "dashboard-contracts-"));
  try {
    await buildOutputs(temporaryDirectory);
    for (const name of outputNames) {
      const generated = await readFile(join(temporaryDirectory, name));
      const tracked = await readFile(join(generatedDirectory, name));
      assert(generated.equals(tracked), `${name} is stale; run npm run contracts:generate`);
    }
  } finally {
    await rm(temporaryDirectory, { recursive: true, force: true });
  }
} else {
  await buildOutputs(generatedDirectory);
}
