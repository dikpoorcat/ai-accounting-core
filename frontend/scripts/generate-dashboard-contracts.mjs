import assert from "node:assert/strict";
import { mkdtemp, readFile, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import Ajv2020 from "ajv/dist/2020.js";
import { _ } from "ajv/dist/compile/codegen/index.js";
import ucs2lengthRuntime from "ajv/dist/runtime/ucs2length.js";
import standaloneCode from "ajv/dist/standalone/index.js";
import { compile } from "json-schema-to-typescript";

const frontendRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const generatedDirectory = resolve(frontendRoot, "src/api/generated");
const schemaPath = resolve(frontendRoot, "../docs/redesign/contracts/dashboard-response-v2.json");
const check = process.argv.slice(2).includes("--check");

// A response contract is browser-visible only after it is intentionally listed here.
const contracts = [
  ["workflow", "Workflow"], ["period_readiness", "PeriodReadiness"],
  ["dashboard_context", "DashboardContext"], ["dashboard_brief", "DashboardBrief"],
  ["dashboard_brief_group", "DashboardBriefGroup"],
  ["dashboard_funds", "DashboardFunds"], ["dashboard_employees", "DashboardEmployees"],
  ["dashboard_assets", "DashboardAssets"], ["dashboard_business_status", "DashboardBusinessStatus"],
  ["dashboard_quarterly_report", "DashboardQuarterlyReport"],
  ["dashboard_brief_delivery", "DashboardBriefDelivery"],
  ["dashboard_funds_delivery", "DashboardFundsDelivery"],
  ["dashboard_employees_delivery", "DashboardEmployeesDelivery"],
  ["dashboard_assets_delivery", "DashboardAssetsDelivery"],
  ["dashboard_quarterly_report_delivery", "DashboardQuarterlyReportDelivery"],
  ["dashboard_period_preparation", "DashboardPeriodPreparation"],
  ["dashboard_close_review", "DashboardCloseReview"], ["report_export_status", "ReportExportStatus"],
  ["browser_security_status", "BrowserSecurityStatus"],
  ["report_export_receipt", "ReportExportReceipt"],
];
const deliveryResponses = new Map([
  ["dashboard_brief_delivery", "DashboardBrief"],
  ["dashboard_funds_delivery", "DashboardFunds"],
  ["dashboard_employees_delivery", "DashboardEmployees"],
  ["dashboard_assets_delivery", "DashboardAssets"],
  ["dashboard_quarterly_report_delivery", "DashboardQuarterlyReport"],
]);
const moduleName = name => name[0].toLowerCase() + name.slice(1);
const banner = "// Generated by scripts/generate-dashboard-contracts.mjs. Do not edit.\n";

function requireSchemaMap(value) {
  assert(value && typeof value === "object" && !Array.isArray(value), "response schema export must be an object");
  for (const [key] of contracts) {
    assert(value[key] && typeof value[key] === "object" && !Array.isArray(value[key]), `missing response schema: ${key}`);
  }
  return value;
}

function validatorCompilationSchema(value) {
  if (Array.isArray(value)) return value.map(validatorCompilationSchema);
  if (!value || typeof value !== "object") return value;
  const normalized = Object.fromEntries(Object.entries(value).map(([key, child]) => [key, validatorCompilationSchema(child)]));
  const discriminator = normalized.discriminator;
  if (discriminator && typeof discriminator === "object" && "propertyName" in discriminator) {
    normalized.type ??= "object";
    normalized.discriminator = { propertyName: discriminator.propertyName };
  }
  return normalized;
}

function generatedValidator(schema, key, name) {
  const ajv = new Ajv2020({ allErrors: true, inlineRefs: false, discriminator: true, code: { esm: true, source: true }, strict: true, validateFormats: false });
  // Ajv does not accept Pydantic's OpenAPI discriminator mapping and requires object types.
  // Keep the exported schema and types intact; change only the validator compilation input.
  const validationSchema = key === "dashboard_brief" || key.endsWith("_delivery")
    ? validatorCompilationSchema(schema)
    : schema;
  if (key.endsWith("_delivery")) {
    // The composed validator below checks ready.response with its existing strict frame validator.
    const readyDefinition = Object.values(validationSchema.$defs).find(definition => definition.properties?.state?.const === "ready");
    assert(readyDefinition, `${key} must define a ready response`);
    readyDefinition.properties.response = true;
  }
  ajv.addKeyword({
    keyword: "x-fen-int64", schemaType: "boolean", type: "string", errors: false,
    code(context) {
      if (context.schema) {
        context.gen.if(_`!/^(0|-?[1-9][0-9]*)$/.test(${context.data})`, () => context.fail(_`true`), () => {
          const amount = context.gen.const("fenAmount", _`BigInt(${context.data})`);
          context.fail(_`${amount} < -9223372036854775808n || ${amount} > 9223372036854775807n`);
        });
      }
    },
  });
  ajv.addSchema(validationSchema, key);
  const baseName = deliveryResponses.get(key);
  const validatorName = baseName ? `validate${name}Envelope` : `validate${name}Response`;
  // Ajv emits this CommonJS runtime even with esm=true. Inline its own Unicode
  // helper so browser validators retain code-point length checks without require.
  const generated = standaloneCode(ajv, { [validatorName]: key }).replaceAll(
    'require("ajv/dist/runtime/ucs2length").default', ucs2lengthRuntime.default.toString(),
  );
  assert(!/\brequire\s*\(/.test(generated), `${key} contains an unsupported CommonJS runtime`);
  if (!baseName) return banner + generated;
  return `${banner}\nimport { validate${baseName}Response } from "./${moduleName(baseName)}.js";\n\n${generated}\n\nexport const validate${name}Response = Object.assign((value) => {\n  if (!${validatorName}(value)) {\n    validate${name}Response.errors = ${validatorName}.errors ?? null;\n    return false;\n  }\n  if (value.state !== "ready") {\n    validate${name}Response.errors = null;\n    return true;\n  }\n  const valid = validate${baseName}Response(value.response);\n  validate${name}Response.errors = valid ? null : validate${baseName}Response.errors ?? null;\n  return valid;\n}, { errors: null });\n`;
}

async function generatedType(schema, name) {
  const responseName = `${name}Response`;
  const generated = await compile(schema, responseName, {
    bannerComment: "", additionalProperties: false, enableConstEnums: false,
    style: { singleQuote: false, semi: true, tabWidth: 2, trailingComma: "all" }, unknownAny: false,
  });
  const indented = generated.trim().split("\n").map(line => line ? `  ${line}` : "").join("\n");
  return `${banner}\nexport namespace ${name}Contract {\n${indented}\n}\n\nexport type ${responseName} = ${name}Contract.${responseName};\n\nimport type { DashboardResponseValidator } from "./dashboardValidatorTypes";\nexport const validate${name}Response: DashboardResponseValidator<${responseName}>;\n`;
}

async function buildOutputs(targetDirectory) {
  const source = (await readFile(schemaPath, "utf8")).replaceAll("\r\n", "\n");
  const schemas = requireSchemaMap(JSON.parse(source));
  const outputs = {
    "dashboardResponseSchemas.json": source,
    "dashboardResponses.d.ts": banner + "\n" + contracts.map(([, name]) => `export type { ${name}Response, ${name}Contract } from "./${moduleName(name)}";`).join("\n") + "\n",
    "dashboardValidators.js": banner + contracts.map(([, name]) => `export { validate${name}Response } from "./${moduleName(name)}.js";`).join("\n") + "\n",
    "dashboardValidators.d.ts": banner + contracts.map(([, name]) => `export { validate${name}Response } from "./${moduleName(name)}.js";`).join("\n") + "\n",
    "dashboardValidatorTypes.d.ts": banner + `\nexport interface DashboardValidationError {\n  instancePath: string;\n  schemaPath: string;\n  keyword: string;\n  params: Record<string, unknown>;\n  message?: string;\n}\n\nexport interface DashboardResponseValidator<T> {\n  (value: unknown): value is T;\n  errors?: DashboardValidationError[] | null;\n}\n`,
  };
  for (const [key, name] of contracts) {
    const module = moduleName(name);
    outputs[`${module}.d.ts`] = await generatedType(schemas[key], name);
    outputs[`${module}.js`] = generatedValidator(schemas[key], key, name);
  }
  await Promise.all(Object.entries(outputs).map(([name, content]) => writeFile(join(targetDirectory, name), content, "utf8")));
  return Object.keys(outputs);
}

if (check) {
  const temporaryDirectory = await mkdtemp(join(tmpdir(), "dashboard-contracts-"));
  try {
    for (const name of await buildOutputs(temporaryDirectory)) {
      const generated = await readFile(join(temporaryDirectory, name));
      const tracked = await readFile(join(generatedDirectory, name));
      assert(generated.equals(tracked), `${name} is stale; run npm run contracts:generate`);
    }
  } finally {
    await rm(temporaryDirectory, { recursive: true, force: true });
  }
} else {
  await buildOutputs(generatedDirectory);
}
